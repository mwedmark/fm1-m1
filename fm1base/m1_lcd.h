/* a character's eight rows, 5 bits each (bit 4 = the leftmost dot) */
static void m1_lcd_glyph(uint32_t ch, uint8_t rows[8])
{
    uint32_t r, c;
    if (ch >= 0x61u && ch <= 0x7Au) {
        for (r = 0; r < 8u; r++)
            rows[r] = m1_font_lower[ch - 0x61u][r];
        return;
    }
    if (ch < 8u) {
        for (r = 0; r < 8u; r++)
            rows[r] = m1_font_custom[ch][r];
        return;
    }
    if (ch < 0x20u || ch > 0x7Eu)
        ch = 0x3Fu;                                          /* '?' */
    for (r = 0; r < 8u; r++) {
        uint8_t v = 0;
        for (c = 0; c < 5u; c++)
            if (r < 7u && (m1_font_cols[ch - 0x20u][c] >> r & 1u))
                v |= (uint8_t)(0x10u >> c);
        rows[r] = v;
    }
}

/* one character at (x, y) in the canvas: s pixels a dot, lit or unlit */
static void m1_lcd_char(int32_t x, int32_t y, int32_t s, uint32_t ch, const m1_lcd_pal_t *p)
{
    uint8_t g[8];
    uint32_t r, c;
    m1_lcd_glyph(ch, g);
    for (r = 0; r < 8u; r++)
        for (c = 0; c < 5u; c++)
            cv_rect(x + (int32_t)c * s, y + (int32_t)r * s, s, s, g[r] >> (4u - c) & 1u ? p->fg : p->off);
}

/* The text of the Program page for the program number n (0..99): row 0 is `PROG  I00 Name`, row 1 the M1's offsets, as the OS draws it with
 * its battery in order (tools/m1_lcd_emu.py). A name is 10 characters; anything outside 0x20..0x7E is shown as a space. */
static void m1_lcd_prog_page(char row[2][40], uint32_t n, const char *name, int bank_ok)
{
    static const char offs[] = "O+00 F+00 L+00 K+00 V+00 A+00 R+00 E+00";
    uint32_t i;
    for (i = 0; i < 40u; i++)
        row[0][i] = row[1][i] = ' ';
    if (!bank_ok) {
        static const char t[] = "NO M1 DATA";
        for (i = 0; t[i]; i++)
            row[1][15 + i] = t[i];
        return;
    }
    row[0][0] = 'P'; row[0][1] = 'R'; row[0][2] = 'O'; row[0][3] = 'G';
    row[0][6] = 'I';
    row[0][7] = (char)('0' + n / 10 % 10);
    row[0][8] = (char)('0' + n % 10);
    for (i = 0; i < 10u && name && name[i]; i++)
        row[0][10 + i] = name[i] >= 0x20 && name[i] <= 0x7E ? name[i] : ' ';
    for (i = 0; offs[i]; i++)
        row[1][i] = offs[i];
}

/* the whole display into the canvas, the top of the glass at y0 (the canvas is 240 wide); returns the glass's height */
static int32_t m1_lcd_draw(uint32_t view, uint32_t col, char row[2][40], int32_t y0)
{
    const m1_lcd_pal_t *p = &m1_lcd_pals[col < M1_COLS ? col : 0];
    int32_t s = view == M1_VIEW_2X20 ? 2 : 1, pad = 2 * s, r, h, x, y, k, half;
    int32_t cw = 6 * s, lh = 9 * s, gap = view == M1_VIEW_2X20 ? 12 : 0;
    h = view == M1_VIEW_2X20 ? 4 * lh + gap + 2 * pad : 2 * lh + 2 * pad;
    cv_rect(0, y0 - 2, 240, h + 4, p->edge);                 /* the bezel */
    cv_rect(0, y0, 240, h, p->bg);
    for (r = 0; r < 2; r++)
        for (half = 0; half < (view == M1_VIEW_2X20 ? 2 : 1); half++) {
            int32_t n = view == M1_VIEW_2X20 ? 20 : 40;
            y = y0 + pad + (view == M1_VIEW_2X20 ? r * (2 * lh + gap) + half * lh : r * lh);
            for (k = 0; k < n; k++) {
                x = k * cw;
                m1_lcd_char(x, y, s, (uint8_t)row[r][half * 20 + k], p);
            }
        }
    return h;
}
