/* The M1's LCD on the FM-1's 240 x 240 screen: 40 x 2 characters of 5 x 8 dots (HD44780-compatible, docs/M1_LCD.md), drawn in two views and
 * three colour schemes. Part of app.c's unity build: cv_begin / cv_rect and RGB come from the platform (gfx.c).
 *
 *   view M1    40 characters across 240 px: one pixel a dot, the display exactly as large as it is on the M1 (a 6 x 9 px cell)
 *   view 2X20  each row split in two halves of 20 characters, two pixels a dot (12 x 18 px cells): four lines, easier to read
 *
 * The colour schemes are taken from photos of the module (the default, yellow-green with dark dots) and two of the replacement
 * displays that are fitted to an M1: blue with white dots and a black one with amber dots. The "off" colour is an unlit dot: the grid
 * the photos show between the lit ones.
 *
 * The glyphs are the HD44780 "A00" set as reconstructed from the datasheet's look: capitals, digits and punctuation from the classic 5 x 7
 * dot font (one byte a column), the lower case and the custom characters (codes 1 and 4..7, the ones the OS loads at start) drawn row by
 * row because their descenders reach the eighth row. Nothing here is copied from Korg's OS. */
