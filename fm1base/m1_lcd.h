#include <stdint.h>

enum { M1_VIEW_M1, M1_VIEW_2X20, M1_VIEWS };
enum { M1_COL_GREEN, M1_COL_BLUE, M1_COL_AMBER, M1_COLS };

typedef struct {
    const char *name;
    uint16_t bg, fg, off, edge;          /* the glass, a lit dot, an unlit dot, the bezel line */
} m1_lcd_pal_t;

